const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  durumAl: () => ipcRenderer.invoke('durum-al'),
  arsivAl: (gun) => ipcRenderer.invoke('arsiv-al', gun),
  gruplarAl: () => ipcRenderer.invoke('gruplar-al'),
  gunSil: (gun, grup) => ipcRenderer.invoke('gun-sil', gun, grup ?? null),
  gecmisIndir: (a) => ipcRenderer.invoke('gecmis-indir', a),
  fotografSil: (yol) => ipcRenderer.invoke('fotograf-sil', yol),
  degisiklikSor: () => ipcRenderer.invoke('degisiklik-sor'),
  gecmisKontrol: (a) => ipcRenderer.invoke('gecmis-kontrol', a),
  senkronizasyonOnayla: () => ipcRenderer.invoke('senkronizasyon-onayla'),
  whatsappCikis: () => ipcRenderer.invoke('whatsapp-cikis'),
  baglan: () => ipcRenderer.invoke('baglan'),
  gruplariGetir: () => ipcRenderer.invoke('gruplari-getir'),
  kucukUret: (p) => ipcRenderer.invoke('kucuk-uret', p),
  topla: (zorla, gecmis = false) => ipcRenderer.invoke('topla', zorla, gecmis),
  durdur: () => ipcRenderer.invoke('durdur'),
  ayarKaydet: (a) => ipcRenderer.invoke('ayar-kaydet', a),
  klasorSec: () => ipcRenderer.invoke('klasor-sec'),
  klasorAc: () => ipcRenderer.invoke('klasor-ac'),
  dosyaGoster: (y) => ipcRenderer.invoke('dosya-goster', y),
  oturumSifirla: () => ipcRenderer.invoke('oturum-sifirla'),
  gecmisiSifirla: () => ipcRenderer.invoke('gecmisi-sifirla'),
  veriKlasoruAc: () => ipcRenderer.invoke('veri-klasoru-ac'),

  onGruplar: (cb) => ipcRenderer.on('gruplar', (_e, v) => cb(v)),
  onQr: (cb) => ipcRenderer.on('qr', (_e, v) => cb(v)),
  onDurum: (cb) => ipcRenderer.on('durum', (_e, v) => cb(v)),
  onDosya: (cb) => ipcRenderer.on('dosya', (_e, v) => cb(v)),
  onSenkron: (cb) => ipcRenderer.on('senkron', (_e, v) => cb(v)),
  onYinelenen: (cb) => ipcRenderer.on('yinelenen', (_e, v) => cb(v)),
  onBitti: (cb) => ipcRenderer.on('bitti', (_e, v) => cb(v)),
  onHata: (cb) => ipcRenderer.on('hata', (_e, v) => cb(v)),
});
